function assertPackageValidation(
  packageId: TripPackageId,
  assemblyReport: TripPackageAssemblyReport,
) {
  if (assemblyReport.status !== "passed") {
    throw new TripPackageLoadError(
      packageId,
      `Trip Package ${packageId} validation 未通过，当前状态为 ${assemblyReport.status ?? "unknown"}。`,
    );
  }

  if (hasValidationIssues(assemblyReport.issues)) {
    throw new TripPackageLoadError(
      packageId,
      `Trip Package ${packageId} validation 存在 issues，暂不进入 Explore。`,
    );
  }
}

function hasValidationIssues(issues: unknown) {
  if (!issues) {
    return false;
  }

  if (Array.isArray(issues)) {
    return issues.length > 0;
  }

  if (typeof issues === "object") {
    return Object.values(issues).some((value) =>
      Array.isArray(value) ? value.length > 0 : Boolean(value),
    );
  }

  return Boolean(issues);
}

export async function loadTripPackage(
  packageId: TripPackageId,
): Promise<LoadedTripPackage> {
  const tripPackage = STATIC_TRIP_PACKAGES[packageId];

  if (!tripPackage) {
    throw new TripPackageLoadError(
      packageId,
      `Trip Package ${packageId} 不在 Wanderly v1.9 白名单中。`,
    );
  }

  assertPackageValidation(packageId, tripPackage.assemblyReport);

  return tripPackage;
}

export async function loadAvailableTripPackages(): Promise<TripPackageLoadResult> {
  const results = await Promise.allSettled(
    AVAILABLE_TRIP_PACKAGE_IDS.map((packageId) => loadTripPackage(packageId)),
  );
  const packages: LoadedTripPackage[] = [];
  const issues: TripPackageLoadResult["issues"] = [];

  results.forEach((result, index) => {
    const packageId = AVAILABLE_TRIP_PACKAGE_IDS[index];

    if (!packageId) {
      return;
    }

    if (result.status === "fulfilled") {
      packages.push(result.value);
      return;
    }

    issues.push({
      packageId,
      message:
        result.reason instanceof Error
          ? result.reason.message
          : `Trip Package ${packageId} 读取失败。`,
      cause: result.reason,
    });
  });

  return {
    packages,
    issues,
  };
}
